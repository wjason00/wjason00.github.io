def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--state", type=Path, default=ROOT / SOURCE)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source_path = args.state.resolve()
    source_bytes = source_path.read_bytes()
    if sha(source_bytes) != EXPECTED_SOURCE_SHA256:
        raise SystemExit("Source hash mismatch; review a new state explicitly before changing the pinned presentation.")
    record = json.loads(source_bytes)
    assert record["stateSha256"] == EXPECTED_STATE_SHA256
    assert record["bundleSha256"] == EXPECTED_BUNDLE_SHA256
    assert sha((ROOT / record["bundle"]).read_bytes()) == EXPECTED_BUNDLE_SHA256
    tissue, fields, categories, count = geometry(record["state"])
    feature = main_svg(tissue, fields, categories)
    panels = {"morphbrain-field.svg": standalone("field", tissue, fields, record), "morphbrain-regions.svg": standalone("regions", tissue, categories, record)}
    receipt = build_receipt(record, source_path, source_bytes, feature, panels, count)
    outputs = {ASSET:feature, **{"assets/portfolio/"+k:v for k,v in panels.items()}, PROVENANCE:(json.dumps(receipt,indent=2,ensure_ascii=True)+"\n").encode("utf-8")}
    for name, data in outputs.items():
        if name.endswith(".svg"):
            ET.fromstring(data)
            assert len(data) < 200000
        target = ROOT / name
        if args.check:
            assert target.read_bytes() == data, f"Generated bytes differ: {name}"
        else:
            target.write_bytes(data)
    assert source_path.read_bytes() == source_bytes
    print(json.dumps({"mode":"checked" if args.check else "generated","outputs":{k:{"bytes":len(v),"sha256":sha(v)} for k,v in outputs.items()},"simulation_run":False},indent=2))


if __name__ == "__main__":
    main()
