def standalone(kind, tissue, paths, source_record):
    label = "Signal fields within model tissue" if kind == "field" else "Broad positional readout"
    metadata = {"provenance": PROVENANCE, "source": SOURCE, "source_sha256": EXPECTED_SOURCE_SHA256,
                "bundle_sha256": EXPECTED_BUNDLE_SHA256, "grid": [96, 144], "view": kind,
                "composition_only": True, "outside": "transparent; nonzero exterior field values omitted"}
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 144" width="480" height="720" role="img" aria-labelledby="panel-title panel-desc">',
             f'<title id="panel-title">Illustrative patterning model: {label}</title>',
             '<desc id="panel-desc">Full 96 by 144 spatial domain. Outside model tissue is transparent. Nonzero field values in the surrounding medium are omitted, not assumed zero. Contours interpolate the same exported grid; categorical cells are exact. No simulation resolution or scientific result is added.</desc>',
             '<metadata>' + escape(json.dumps(metadata, separators=(",", ":"), ensure_ascii=True)) + '</metadata>']
    if kind == "field":
        parts += ['<defs>', f'<clipPath id="tissue-clip" clipPathUnits="userSpaceOnUse"><path d="{tissue}"/></clipPath>', '</defs>']
    parts += paths + ['</svg>']
    return ("\n".join(parts) + "\n").encode("utf-8")


