def sha(data):
    return hashlib.sha256(data).hexdigest()


def runs_path(binary):
    """Retain every classified/source/tissue cell as exact row-run rectangles."""
    result = []
    for y, row in enumerate(binary):
        padded = np.r_[False, row, False]
        cuts = np.flatnonzero(padded[1:] != padded[:-1])
        for start, end in zip(cuts[0::2], cuts[1::2]):
            result.append(f"M{start} {y}h{end-start}v1H{start}Z")
    return "".join(result)


def poly_path(points, codes):
    out = []
    for (x, y), code in zip(points, codes):
        if code == 1:
            out.append(f"M{x:.2f} {y:.2f}")
        elif code == 2:
            out.append(f"L{x:.2f} {y:.2f}")
        elif code == 79:
            out.append("Z")
        else:
            raise ValueError(f"Unexpected contour code: {code}")
    return "".join(out)


def geometry(state):
    w, h = state["width"], state["height"]
    assert (w, h) == (96, 144)
    mask = np.asarray(state["tissueMask"], dtype=bool).reshape(h, w)
    fates = np.asarray(state["fates"], dtype=np.uint8).reshape(h, w)
    tissue = runs_path(mask)
    fields = [f'<path d="{tissue}" fill="#d2ded4"/>', '<g clip-path="url(#tissue-clip)">']
    count = 0
    for name in ["bmp", "shh"]:
        field = np.asarray(state[name], dtype=float).reshape(h, w)
        assert np.isfinite(field).all() and field.min() >= 0 and field.max() <= 25
        # Fixed presentation levels on the unchanged exported values; no normalization.
        cg = contourpy.contour_generator(x=np.arange(w)+.5, y=np.arange(h)+.5, z=field, fill_type="OuterCode", line_type="Separate")
        for i, level in enumerate(LEVELS):
            pts, codes = cg.filled(level, 25.000001)
            for points, code in zip(pts, codes):
                d = poly_path(points, code)
                if d:
                    fields.append(f'<path d="{d}" fill="{COLOURS[name]}" fill-opacity="{[.065,.09,.14,.22][i]}"/>')
            for line in cg.lines(level):
                if len(line) < 2:
                    continue
                d = "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in line)
                fields.append(f'<path d="{d}" fill="none" stroke="{COLOURS[name]}" stroke-opacity="{[.45,.61,.76,.94][i]}" stroke-width="{[.19,.23,.29,.36][i]}" stroke-linejoin="round" stroke-linecap="round"/>')
                count += 1
    for name in ["bmp", "shh"]:
        cells = np.asarray(state[name+"SourceMask"], dtype=bool).reshape(h, w) & mask
        fields.append(f'<path d="{runs_path(cells)}" fill="{COLOURS[name]}" fill-opacity=".85"/>')
    fields.append("</g>")
    categories = []
    for ids, name in [([1, 2], "dorsal"), ([3], "intermediate"), ([4, 5], "ventral")]:
        cells = np.isin(fates, ids) & mask
        categories.append(f'<path d="{runs_path(cells)}" fill="{COLOURS[name]}" shape-rendering="crispEdges"/>')
    return tissue, fields, categories, count


