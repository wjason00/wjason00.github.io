// Derive display points from an already-public CC0 atlas surface; no solver.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceName = 'demos/morphbrain/atlas/week-36.glb';
const decoderName = 'demos/morphbrain/draco/draco_wasm_wrapper.js';
const wasmName = 'demos/morphbrain/draco/draco_decoder.wasm';
const sha = value => createHash('sha256').update(value).digest('hex');
const source = readFileSync(join(root, sourceName));
if (source.toString('ascii', 0, 4) !== 'glTF' || source.readUInt32LE(4) !== 2) throw Error('Expected GLB v2');
const jsonLength = source.readUInt32LE(12);
const gltf = JSON.parse(source.toString('utf8', 20, 20 + jsonLength));
const binaryStart = 20 + jsonLength + 8;
const primitive = gltf.meshes[0].primitives[0];
const extension = primitive.extensions.KHR_draco_mesh_compression;
const view = gltf.bufferViews[extension.bufferView];
const packed = source.subarray(binaryStart + (view.byteOffset || 0), binaryStart + (view.byteOffset || 0) + view.byteLength);

const wrapperPath = join(root, decoderName);
const wrapper = readFileSync(wrapperPath, 'utf8');
const module = { exports: {} };
// Run the shipped UMD decoder in its Node/CommonJS mode, with local WASM only.
new Function('module', 'exports', 'require', '__dirname', '__filename', wrapper)(
  module, module.exports, createRequire(import.meta.url), dirname(wrapperPath), wrapperPath,
);
const draco = await module.exports({ wasmBinary: readFileSync(join(root, wasmName)) });
const decoder = new draco.Decoder();
const buffer = new draco.DecoderBuffer();
buffer.Init(new Int8Array(packed), packed.length);
const mesh = new draco.Mesh();
const status = decoder.DecodeBufferToMesh(buffer, mesh);
if (!status.ok() || !mesh.ptr) throw Error('Draco surface decode failed');
const attribute = decoder.GetAttributeByUniqueId(mesh, extension.attributes.POSITION);
const values = new draco.DracoFloat32Array();
if (!decoder.GetAttributeFloatForAllPoints(mesh, attribute, values)) throw Error('Position decode failed');
const vertexCount = mesh.num_points();
const min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
for (let i = 0; i < vertexCount; i++) for (let axis = 0; axis < 3; axis++) {
  const value = values.GetValue(i * 3 + axis);
  if (!Number.isFinite(value)) throw Error('Non-finite source point');
  min[axis] = Math.min(min[axis], value); max[axis] = Math.max(max[axis], value);
}
const centre = min.map((value, axis) => (value + max[axis]) / 2);
const scale = Math.max(...max.map((value, axis) => value - min[axis])) / 2;
const count = 4096;
const points = new Float32Array(count * 3);
const indices = [];
for (let i = 0; i < count; i++) {
  const index = Math.floor(i * (vertexCount - 1) / (count - 1));
  indices.push(index);
  for (let axis = 0; axis < 3; axis++) points[i * 3 + axis] = (values.GetValue(index * 3 + axis) - centre[axis]) / scale;
}
const bytes = Buffer.from(points.buffer);
const metadata = {
  title: 'Interactive atlas surface study', source: sourceName, sourceSha256: sha(source),
  dataset: 'dHCP fetal surface atlas', doi: '10.12751/g-node.qj5hs7', license: 'CC0-1.0',
  population: 'population-average', surface: 'white-matter', week: 36,
  sourceVertices: vertexCount, displayPoints: count, encoding: 'Float32 XYZ, little endian, base64',
  sampling: 'vertex index floor(i * (N - 1) / (4096 - 1)); not uniform surface-area sampling',
  normalization: { centre, scale, rule: 'Subtract bounding-box centre; divide all axes by the same half maximum extent' },
  sourceDisplayEncoding: 'Source GLB already uses atlas display axes x,z,y and centroid/max-radius scaling; this export adds only an isotropic display fit',
  pointBytesSha256: sha(bytes),
  limits: 'Interface artwork from one atlas surface. Cursor displacement/lighting is decorative, not neural activity, measured dynamics, development or validation of anatomical orientation.',
};
const destination = join(root, 'assets/portfolio');
mkdirSync(destination, { recursive: true });
const data = `// Generated by scripts/derive-hero-surface.mjs from the public CC0 atlas.\nexport const metadata = Object.freeze(${JSON.stringify(metadata)});\nconst encoded = '${bytes.toString('base64')}';\nconst decoded = Uint8Array.from(atob(encoded), character => character.charCodeAt(0));\nexport const positions = new Float32Array(decoded.buffer);\n`;
writeFileSync(join(destination, 'brain-surface-data.js'), data);
writeFileSync(join(destination, 'brain-surface-source.json'), JSON.stringify({ ...metadata, decoder: { wrapper: decoderName, wrapperSha256: sha(Buffer.from(wrapper)), wasm: wasmName, wasmSha256: sha(readFileSync(join(root, wasmName))) }, selectedVertexIndices: indices }, null, 2) + '\n');

// Static vector fallback uses the same sampled points and a fixed display view.
const yaw = .55, pitch = -.18, cy = Math.cos(yaw), sy = Math.sin(yaw), cx = Math.cos(pitch), sx = Math.sin(pitch);
const projected = [];
for (let i = 0; i < count; i++) {
  const x = points[i * 3], y = points[i * 3 + 1], z = points[i * 3 + 2];
  const x1 = x * cy + z * sy, z1 = -x * sy + z * cy;
  const y1 = y * cx - z1 * sx, depth = y * sx + z1 * cx;
  projected.push({ x: 400 + x1 * 260, y: 330 - y1 * 260, z: depth });
}
projected.sort((a, b) => a.z - b.z);
const circles = projected.map(p => `<circle cx="${p.x.toFixed(1)}" cy="${p.y.toFixed(1)}" r="1.3" opacity="${(.3 + (p.z + 1) * .27).toFixed(2)}"/>`).join('');
writeFileSync(join(destination, 'brain-surface.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 660" role="img" aria-labelledby="t d"><title id="t">Atlas surface point study</title><desc id="d">A static display of 4096 sampled points from a public population-average white-matter surface, 36 weeks. Interface illustration, not neural activity.</desc><g fill="#74a995">${circles}</g></svg>\n`);
for (const object of [values, mesh, buffer, decoder]) draco.destroy(object);
console.log(JSON.stringify({ source: sourceName, sourceSha256: metadata.sourceSha256, sourceVertices: vertexCount, displayPoints: count, dataBytes: Buffer.byteLength(data), pointBytes: bytes.length }));
